# Index by ID for O(1) lookup
EXERCISE_BY_ID: dict[str, Exercise] = {ex.id: ex for ex in EXERCISE_LIBRARY}


def get_exercises_for_tier(tier: EquipmentTier) -> list[Exercise]:
    """Return all exercises available at the given equipment tier."""
    return [ex for ex in EXERCISE_LIBRARY if ex.equipment_tier.value <= tier.value]


def get_exercises_for_muscle(muscle: MuscleGroup, tier: EquipmentTier,
                             role: MuscleRole = MuscleRole.PRIMARY) -> list[Exercise]:
    """Return exercises that target a specific muscle at a given role."""
    return [
        ex for ex in EXERCISE_LIBRARY
        if ex.equipment_tier.value <= tier.value
        and any(ma.muscle == muscle and ma.role == role for ma in ex.muscle_activations)
    ]


def get_exercises_for_pattern(pattern: MovementPattern, tier: EquipmentTier) -> list[Exercise]:
    """Return exercises matching a movement pattern at the given tier."""
    return [
        ex for ex in EXERCISE_LIBRARY
        if ex.equipment_tier.value <= tier.value and ex.movement_pattern == pattern
    ]
